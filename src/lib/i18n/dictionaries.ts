/**
 * Synchronously retrieves embedded initial dictionary for server-side rendering or instant fallback.
 */
export function getInitialDictionary(locale: string): Dictionary {
  return dictionaryCache[locale] || dictionaryCache[FALLBACK_LOCALE] || dictionaryCache[DEFAULT_LOCALE];
}

/**
 * Loads the dictionary for a given locale with fallback support to English.
 */
export async function getDictionary(locale: string): Promise<Dictionary> {
  if (dictionaryCache[locale]) {
    return dictionaryCache[locale];
  }

  try {
    const res = await fetch(`/locales/${locale}.json`);
    if (res.ok) {
      const data = (await res.json()) as Dictionary;
      dictionaryCache[locale] = data;
      return data;
    } else {
      console.warn(`[i18n] Failed to fetch /locales/${locale}.json (HTTP ${res.status}), using fallback.`);
    }
  } catch {
    console.warn(`[i18n] Failed to load locale dictionary: ${locale}, using fallback.`);
  }

  // Fallback to English dictionary
  return dictionaryCache[FALLBACK_LOCALE] || dictionaryCache[DEFAULT_LOCALE];
}

/**
 * Resolves a nested key string (e.g. 'common.welcome') against a dictionary object,
 * with English fallback and parameter interpolation (e.g. { count: 5 }).
 */
export function translateKey(
  dict: Dictionary | null,
  fallbackDict: Dictionary | null,
  key: string,
  params?: Record<string, string | number>
): string {
  const keys = key.split(".");
  let result: unknown = dict;

  for (const k of keys) {
    if (result && typeof result === "object" && k in result) {
      result = (result as Record<string, unknown>)[k];
    } else {
      result = undefined;
      break;
    }
  }

  // Fallback lookup if key not found in primary dictionary
  if (result === undefined && fallbackDict) {
    let fallbackResult: unknown = fallbackDict;
    for (const k of keys) {
      if (fallbackResult && typeof fallbackResult === "object" && k in fallbackResult) {
        fallbackResult = (fallbackResult as Record<string, unknown>)[k];
      } else {
        fallbackResult = undefined;
        break;
      }
    }
    result = fallbackResult;
  }

  if (typeof result !== "string") {
    return key; // Return raw key string safely without crashing
  }

  let formattedResult = result;

  // Parameter replacement: {variable}
  if (params) {
    Object.entries(params).forEach(([paramKey, paramVal]) => {
      formattedResult = formattedResult.replace(
        new RegExp(`\\{${paramKey}\\}`, "g"),
        String(paramVal)
      );
    });
  }

  return formattedResult;
}
